function line(y: number, cells: [number, string][]): TextItem[] {
  return cells.map(([x, str]) => ({ x, y, str, page: 1 }))
}

function holdingRow(y: number, values: string[]): TextItem[] {
  return line(y, values.map((v, i) => [X[i], v] as [number, string]))
}

